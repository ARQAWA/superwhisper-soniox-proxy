export interface PacOptions {
  proxyHost: string;
  proxyPort: number;
  allowedHosts: string[];
}

export function normalizeHost(host: string): string {
  return host.trim().toLowerCase().replace(/\.$/, "");
}

export function parseAllowedHosts(value: string): string[] {
  const seen = new Set<string>();
  const hosts: string[] = [];
  for (const raw of value.split(",")) {
    const host = normalizeHost(raw);
    if (!host || seen.has(host)) continue;
    seen.add(host);
    hosts.push(host);
  }
  return hosts;
}

/**
 * Match the same rules the generated PAC uses: exact hosts plus `*.` suffix
 * entries. Keep this in sync with buildPac().
 */
export function hostMatchesAllowlist(host: string, allowedHosts: string[]): boolean {
  const candidate = normalizeHost(host);
  if (!candidate) return false;
  for (const entry of allowedHosts) {
    if (entry.startsWith("*.")) {
      const suffix = entry.slice(1);
      if (candidate.length > suffix.length && candidate.endsWith(suffix)) return true;
    } else if (candidate === entry) {
      return true;
    }
  }
  return false;
}

function pacRule(entry: string): { host: string; suffix: string } {
  if (entry.startsWith("*.")) {
    return { host: "", suffix: entry.slice(1) };
  }
  return { host: entry, suffix: "" };
}

/**
 * Generate a PAC file that sends only the allowlisted hosts to the local
 * proxy. Every other request stays DIRECT, so unrelated apps never touch the
 * proxy or its logs.
 */
export function buildPac(options: PacOptions): string {
  const rules = parseAllowedHosts(options.allowedHosts.join(",")).map(pacRule);
  const proxy = `PROXY ${options.proxyHost}:${options.proxyPort}; DIRECT`;
  const ruleLines = rules
    .map((rule) =>
      rule.suffix
        ? `    { host: "", suffix: ${JSON.stringify(rule.suffix)} }`
        : `    { host: ${JSON.stringify(rule.host)}, suffix: "" }`,
    )
    .join(",\n");
  return [
    "// Generated by the SuperWhisper Soniox proxy. Do not edit by hand.",
    "function FindProxyForURL(url, host) {",
    '  host = String(host || "").toLowerCase();',
    '  if (host.charAt(host.length - 1) === ".") host = host.slice(0, -1);',
    "  var rules = [",
    ruleLines,
    "  ];",
    "  for (var i = 0; i < rules.length; i += 1) {",
    "    var rule = rules[i];",
    "    if (rule.suffix) {",
    "      if (host.length > rule.suffix.length && host.slice(-rule.suffix.length) === rule.suffix) {",
    `        return ${JSON.stringify(proxy)};`,
    "      }",
    "    } else if (host === rule.host) {",
    `      return ${JSON.stringify(proxy)};`,
    "    }",
    "  }",
    '  return "DIRECT";',
    "}",
    "",
  ].join("\n");
}
